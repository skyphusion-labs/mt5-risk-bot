def timeframe_code(timeframe: str | int) -> int:
    if isinstance(timeframe, int):
        return timeframe
    key = str(timeframe).upper()
    if key not in TIMEFRAME_BY_NAME:
        raise ValueError(f"unknown timeframe {timeframe!r}")
    return TIMEFRAME_BY_NAME[key]

